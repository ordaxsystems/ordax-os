export const FIRST_RUN_TRANSLATION_LOCALES = Object.freeze(Object.keys(TABLES));

function dynamic(locale, text) {
  if (locale === "en-US") {
    if (text.startsWith("Senha de ")) return "Password for " + text.slice("Senha de ".length);
    if (text.startsWith("Conta autenticada como ")) return "Signed in as " + text.slice("Conta autenticada como ".length);
  }
  if (locale === "es-ES") {
    if (text.startsWith("Senha de ")) return "Contraseña de " + text.slice("Senha de ".length);
    if (text.startsWith("Conta autenticada como ")) return "Cuenta autenticada como " + text.slice("Conta autenticada como ".length);
  }
  if (locale === "de-DE") {
    if (text.startsWith("Senha de ")) return "Passwort für " + text.slice("Senha de ".length);
    if (text.startsWith("Conta autenticada como ")) return "Angemeldet als " + text.slice("Conta autenticada como ".length);
  }
  if (locale === "fr-FR") {
    if (text.startsWith("Senha de ")) return "Mot de passe pour " + text.slice("Senha de ".length);
    if (text.startsWith("Conta autenticada como ")) return "Connecté en tant que " + text.slice("Conta autenticada como ".length);
  }
  return text;
}

export function translateFirstRunText(locale, text) {
  if (typeof text !== "string") return text;
  if (locale === "pt-BR") return text;
  return TABLES[locale]?.[text] ?? dynamic(locale, text);
}
