export const SPACE_TYPE_CATALOG = validateSpaceTypeCatalog(rawCatalog);

export function getSpaceType(domain, subtype) {
  return SPACE_TYPE_CATALOG.types.find((type) => type.domain === domain && type.subtype === subtype) ?? null;
}

export function getSpaceTypeByProfile(profilePack) {
  if (typeof profilePack !== "string" || !profilePack) return null;
  return SPACE_TYPE_CATALOG.types.find((type) => type.profileBindings.includes(profilePack)) ?? null;
}
